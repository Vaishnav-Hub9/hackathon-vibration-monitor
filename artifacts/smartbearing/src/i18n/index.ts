const LANGUAGE_KEY = 'smartbearing-language';

export function getLanguage(): Language {
  const value = localStorage.getItem(LANGUAGE_KEY);
  return value === 'hi' || value === 'te' || value === 'ta' ? value : 'en';
}

export function setLanguage(language: Language) {
  localStorage.setItem(LANGUAGE_KEY, language);
  window.dispatchEvent(new CustomEvent('smartbearing-language-change'));
}

export function useI18n() {
  const [language, setCurrentLanguage] = useState<Language>(() => getLanguage());
  useEffect(() => {
    const handleChange = () => setCurrentLanguage(getLanguage());
    window.addEventListener('smartbearing-language-change', handleChange);
    return () => window.removeEventListener('smartbearing-language-change', handleChange);
  }, []);
  return { language, setLanguage, t: (key: string) => translations[language][key] || translations.en[key] || key };
}
